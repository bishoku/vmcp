import { auditSettings } from './audit-fixtures'
import { expect, test } from '@playwright/test'
import { server, upstream } from '../src/connections/fixtures'
for(const width of [1280,390])test(`guidance draft, preview and save at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900})
 const writes:Record<string,unknown>[]=[]
 const guidance={instructions:'Start with {{tool:lookup}}',resources:[],prompts:[],toolReferences:[{key:'lookup',upstream:'alpha',tool:'lookup'}],upstreamInstructions:[]}
 await page.route('**/auth/config',r=>r.fulfill({json:{oidc:false}}))
 await page.route('**/api/v1/**',r=>{
 if(new URL(r.request().url()).pathname.endsWith('/audit-settings'))return r.fulfill({json:auditSettings})

  const req=r.request(),path=new URL(req.url()).pathname
  if(path.endsWith('/me'))return r.fulfill({status:req.headers().authorization?200:401,json:{role:'admin',name:'Tester'}})
  if(req.method()==='PUT'){writes.push(req.postDataJSON());return r.fulfill({json:{...server,...req.postDataJSON(),version:server.version+1}})}
  if(path.endsWith('/virtual-servers'))return r.fulfill({json:{items:[{...server,hasGuidance:true}]}})
  if(path.endsWith(`/virtual-servers/${server.slug}`))return r.fulfill({json:{...server,hasGuidance:true,guidance}})
  if(path.endsWith('/upstreams'))return r.fulfill({json:{items:[upstream]}})
  if(path.endsWith('/tools'))return r.fulfill({json:{items:[{name:'lookup',description:'Find customer'}]}})
  if(path.endsWith('/catalog'))return r.fulfill({json:{resources:[],resourceTemplates:[],prompts:[],capabilities:{},instructions:'Remote guide'}})
  return r.fulfill({json:{items:[]}})
 })
 await page.goto(`/virtual-servers/${server.slug}/edit`)
 await page.getByLabel('Admin token').fill('test');await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.locator('summary').filter({hasText:'Agent guidance'}).click()
 await expect(page.getByText('Start with {{tool:lookup}}',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Add resource',exact:true}).click()
 const item=page.getByRole('dialog',{name:'Add resource',exact:true})
 await item.getByLabel('Identifier',{exact:true}).fill('workflow-guide')
 await item.getByLabel('Title',{exact:true}).fill('Workflow guide')
 await item.getByRole('button',{name:'Edit resource content',exact:true}).click()
 const content=page.getByRole('dialog',{name:'Resource content',exact:true})
 await content.getByRole('textbox',{name:'Resource content',exact:true}).fill('First {{tool:lookup}}. Then summarize.\n'+ 'Detailed instructions. '.repeat(80))
 await content.getByRole('button',{name:'Agent preview',exact:true}).click()
 await expect(content.locator('pre')).not.toContainText('{{tool:lookup}}')
 await page.screenshot({path:test.info().outputPath(`resource-preview-${width}.png`),animations:'disabled'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(writes).toHaveLength(0)
 await content.getByRole('button',{name:'Apply to draft',exact:true}).click()
 await item.getByRole('button',{name:'Apply to draft',exact:true}).click()
 await expect(page.getByText('Workflow guide',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Add prompt',exact:true}).click()
 const prompt=page.getByRole('dialog',{name:'Add prompt',exact:true})
 await prompt.getByLabel('Identifier',{exact:true}).fill('triage')
 await prompt.getByRole('button',{name:'Add argument',exact:true}).click()
 await prompt.getByLabel('Argument name',{exact:true}).fill('topic')
 await prompt.getByLabel('Required argument',{exact:true}).check()
 await prompt.getByRole('button',{name:'Edit message 1',exact:true}).click()
 const message=page.getByRole('dialog',{name:'Message 1',exact:true})
 await message.getByRole('textbox',{name:'Message 1',exact:true}).fill('Use {{tool:lookup}} for {{arg:topic}}')
 await message.getByRole('button',{name:'Apply to draft',exact:true}).click()
 await prompt.getByRole('button',{name:'Agent preview',exact:true}).click()
 await prompt.getByLabel('topic',{exact:true}).fill('Acme')
 await expect(prompt.locator('pre')).toContainText('for Acme')
 await prompt.getByRole('button',{name:'Apply to draft',exact:true}).click()
 await page.getByLabel('Upstream source',{exact:true}).selectOption('alpha')
 await page.getByRole('button',{name:'Include instructions',exact:true}).click()
 await expect(page.getByText('Remote guide',{exact:true})).toBeVisible()
 expect(writes).toHaveLength(0)
 await page.getByRole('button',{name:'Save',exact:true}).click()
 await expect.poll(()=>writes.length).toBe(1)
 expect(writes[0].guidance).toMatchObject({instructions:guidance.instructions,toolReferences:guidance.toolReferences,upstreamInstructions:['alpha'],resources:[{name:'workflow-guide',enabled:true}],prompts:[{name:'triage',messages:[{role:'user',text:'Use {{tool:lookup}} for {{arg:topic}}'}]}]})
})
